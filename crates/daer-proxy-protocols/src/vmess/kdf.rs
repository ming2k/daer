//! The VMess KDF, which is a **nested HMAC built by aliasing hashers**, not HKDF.
//!
//! # Why this module reproduces Go's HMAC instead of composing `hmac`
//!
//! `aead/kdf.go` is nine lines, and its meaning is a property of Go's `hash.Hash` interface:
//!
//! ```go
//! hmacf := hmac.New(sha256.New, []byte(KDFSaltConstVMessAEADKDF))
//! for _, v := range path {
//!     first := true
//!     hmacf = hmac.New(func() hash.Hash {
//!         if first { first = false; return hash2{hmacf} }   // ← the previous HMAC, as a hash
//!         return hmacf
//!     }, []byte(v))
//! }
//! hmacf.Write(key)
//! return hmacf.Sum(nil)
//! ```
//!
//! `hash2{hmacf}` hands the *previous HMAC object* to the next HMAC as its **inner hash
//! function**. Every subsequent `Write` therefore lands inside the previous level's inner
//! hasher, and every `Reset` re-primes that level with its own `ipad`. The result is not
//! `HMAC(HMAC(salt, v), key)` and not HKDF: for a one-component path it expands to
//!
//! ```text
//!   HMAC_S(key)  computed, then the level-1 HMAC writes `opad_v` into it and re-sums
//! ```
//!
//! and each further component nests one more `ipad`/`opad` pair around the whole thing.
//! Substituting HKDF, or `HMAC(previous, component)`, produces 32 bytes of the right length
//! that no VMess server accepts — and the failure is a silent decrypt error on the node,
//! indistinguishable from a wrong UUID.
//!
//! `hmac` (the Rust crate) fixes its inner hash at compile time, so a dynamically nested HMAC
//! cannot be expressed with it. This module therefore carries a small, faithful transcription of
//! `crypto/hmac/hmac.go`'s state machine, with [`NestedHash::Mac`] as Go's `hash2`. The tests
//! assert the reference implementation's **own** output for six derivations, generated by
//! running `aead.KDF`/`aead.KDF16` from `Xray-core`.

use sha2::{Digest as _, Sha256};

/// SHA-256's block size, which is the pad length Go's HMAC uses.
const BLOCK_SIZE: usize = 64;

/// One of the reference's salt strings.
///
/// Spelled exactly: they are HMAC *keys*, and one character changes every derived key.
pub const SALT_AUTH_ID_ENCRYPTION_KEY: &str = "AES Auth ID Encryption";
pub const SALT_AEAD_RESP_HEADER_LEN_KEY: &str = "AEAD Resp Header Len Key";
pub const SALT_AEAD_RESP_HEADER_LEN_IV: &str = "AEAD Resp Header Len IV";
pub const SALT_AEAD_RESP_HEADER_PAYLOAD_KEY: &str = "AEAD Resp Header Key";
pub const SALT_AEAD_RESP_HEADER_PAYLOAD_IV: &str = "AEAD Resp Header IV";
pub const SALT_VMESS_AEAD_KDF: &str = "VMess AEAD KDF";
pub const SALT_HEADER_PAYLOAD_AEAD_KEY: &str = "VMess Header AEAD Key";
pub const SALT_HEADER_PAYLOAD_AEAD_IV: &str = "VMess Header AEAD Nonce";
pub const SALT_HEADER_PAYLOAD_LENGTH_AEAD_KEY: &str = "VMess Header AEAD Key_Length";
pub const SALT_HEADER_PAYLOAD_LENGTH_AEAD_IV: &str = "VMess Header AEAD Nonce_Length";
pub const SALT_AUTHENTICATED_LENGTH: &str = "auth_len";

/// Clones a `NestedHash`, keeping the shared handle shared.
///
/// A `Mac` arm clones the `Rc`, not the MAC: Go passes one object around with a pointer, and the
/// state machine depends on that (a clone would give the outer hasher a private copy of state
/// that the next level still writes into).
fn clone_nested(hash: &NestedHash) -> NestedHash {
    match hash {
        NestedHash::Sha256(hasher) => NestedHash::Sha256(hasher.clone()),
        NestedHash::Mac(mac) => NestedHash::Mac(std::rc::Rc::clone(mac)),
    }
}

/// Go's `hash2`: a `hash.Hash` whose every operation is another HMAC's inner half.
///
/// This is the whole trick of the reference's KDF. It is a shared handle rather than a clone:
/// Go passes the same object, and the state machine relies on that (every use is preceded by a
/// `Reset`, which re-primes the level with its own `ipad`).
#[derive(Debug)]
enum NestedHash {
    Sha256(Sha256),
    /// `hash2{mac}` — forwards to the wrapped MAC's *inner* hasher.
    Mac(std::rc::Rc<std::cell::RefCell<GoMac>>),
}

impl NestedHash {
    fn reset(&mut self) {
        match self {
            Self::Sha256(hasher) => *hasher = Sha256::new(),
            Self::Mac(mac) => mac.borrow_mut().reset(),
        }
    }

    fn write(&mut self, data: &[u8]) {
        match self {
            Self::Sha256(hasher) => hasher.update(data),
            Self::Mac(mac) => mac.borrow_mut().write(data),
        }
    }

    fn sum(&self) -> [u8; 32] {
        match self {
            Self::Sha256(hasher) => hasher.clone().finalize().into(),
            Self::Mac(mac) => mac.borrow().sum(),
        }
    }
}

/// A transcription of `crypto/hmac.HMAC` for SHA-256.
#[derive(Debug)]
struct GoMac {
    inner: NestedHash,
    outer: NestedHash,
    ipad: [u8; BLOCK_SIZE],
    opad: [u8; BLOCK_SIZE],
}

impl GoMac {
    /// `hmac.New(h, key)` where `h` is an already-built hasher factory.
    ///
    /// Go calls the factory twice — once for the inner and once for the outer hasher — and both
    /// return the *same* object when the factory is `hash2{hmacf}`. That sharing is modelled by
    /// the `Rc<RefCell<…>>` inside [`NestedHash::Mac`].
    fn new(make_hash: &dyn Fn() -> NestedHash, key: &[u8]) -> Self {
        let mut inner = make_hash();
        let mut outer = make_hash();

        let mut padded = [0u8; BLOCK_SIZE];
        if key.len() > BLOCK_SIZE {
            // Go hashes an over-long key with the *outer* hasher first.
            outer.write(key);
            padded[..32].copy_from_slice(&outer.sum());
            outer.reset();
        } else {
            padded[..key.len()].copy_from_slice(key);
        }
        let mut ipad = padded;
        let mut opad = padded;
        for byte in &mut ipad {
            *byte ^= 0x36;
        }
        for byte in &mut opad {
            *byte ^= 0x5c;
        }
        // Go's `New` ends with `hm.inner.Write(hm.ipad)`, and that line is what primes the inner
        // hasher. Omitting it produces a plain `SHA(key)` instead of an HMAC, which is a valid
        // 32-byte value that no server derives.
        inner.write(&ipad);
        Self {
            inner,
            outer,
            ipad,
            opad,
        }
    }

    /// `Write`: every byte goes to the inner hasher.
    fn write(&mut self, data: &[u8]) {
        self.inner.write(data);
    }

    /// `Reset`: re-prime the inner hasher with `ipad`.
    fn reset(&mut self) {
        self.inner.reset();
        let ipad = self.ipad;
        self.inner.write(&ipad);
    }

    /// `Sum`: the inner digest, then `opad ‖ digest` through the outer hasher.
    ///
    /// The outer hasher is reset first, exactly as Go does: at the next nesting level it is
    /// somebody else's *inner* hasher and carries that level's bytes. Taking `&self` (rather than
    /// `&mut self`) is possible because the *whole state* is cloned: Go mutates the outer hasher
    /// here, and cloning is what makes that observable behaviour identical without requiring
    /// exclusive access from a shared `Rc`.
    fn sum(&self) -> [u8; 32] {
        let inner_digest = self.inner.sum();
        let mut outer = clone_nested(&self.outer);
        outer.reset();
        outer.write(&self.opad);
        outer.write(&inner_digest);
        outer.sum()
    }
}

/// `aead.KDF(key, path...)`.
#[must_use]
pub fn kdf(key: &[u8], path: &[&str]) -> [u8; 32] {
    let components: Vec<Vec<u8>> = path.iter().map(|part| part.as_bytes().to_vec()).collect();
    kdf_components(key, &components)
}

/// `aead.KDF(key, path...)` with **byte** path components.
///
/// Go's `KDF` takes `...string`, and a Go string is a byte slice: the reference passes `AuthID`
/// and the connection nonce directly. Any component that is not valid UTF-8 would be mangled by a
/// `&str` round trip, which is most of them, so this is the entry point the AEAD header uses.
#[must_use]
pub fn kdf_components(key: &[u8], path: &[Vec<u8>]) -> [u8; 32] {
    let plain = || NestedHash::Sha256(Sha256::new());
    let mut mac = GoMac::new(&plain, SALT_VMESS_AEAD_KDF.as_bytes());
    for component in path {
        // Each level's inner *and* outer hasher is the previous level's MAC — the `hash2{hmacf}`
        // of the reference, shared rather than copied.
        let previous = std::rc::Rc::new(std::cell::RefCell::new(mac));
        let make = {
            let previous = std::rc::Rc::clone(&previous);
            move || NestedHash::Mac(std::rc::Rc::clone(&previous))
        };
        mac = GoMac::new(&make, component);
    }
    mac.write(key);
    mac.sum()
}

/// `aead.KDF16(key, path...)`: the first 16 bytes of [`kdf`].
#[must_use]
pub fn kdf16(key: &[u8], path: &[&str]) -> [u8; 16] {
    let full = kdf(key, path);
    let mut out = [0u8; 16];
    out.copy_from_slice(&full[..16]);
    out
}

/// The user's `cmdKey`: `MD5(uuid ‖ "c48619fe-8f02-49e0-b9e9-edf763e17e21")`.
///
/// The trailing constant is the reference's (`common/protocol/id.go`). It is not a random salt:
/// changing it makes every VMess node reject the session.
#[must_use]
pub fn cmd_key(uuid: &[u8; 16]) -> [u8; 16] {
    use md5::{Digest as _, Md5};

    let mut hasher = Md5::new();
    hasher.update(uuid);
    hasher.update(b"c48619fe-8f02-49e0-b9e9-edf763e17e21");
    hasher.finalize().into()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Keys are `0x00..0x0f`, and every expectation was produced by running
    /// `aead.KDF`/`aead.KDF16` from `Xray-core` on exactly that key.
    ///
    /// These are the falsifier for the whole module. An HKDF, a single HMAC, or a path component
    /// read as `info` yields a plausible 32-byte value that no VMess server accepts, and the
    /// resulting error is indistinguishable from a wrong UUID — so the only honest test is the
    /// reference's own bytes.
    fn key() -> [u8; 16] {
        let mut key = [0u8; 16];
        for (index, byte) in key.iter_mut().enumerate() {
            *byte = index as u8;
        }
        key
    }

    fn hex(bytes: &[u8]) -> String {
        bytes.iter().map(|byte| format!("{byte:02x}")).collect()
    }

    #[test]
    fn the_empty_path_is_one_hmac_under_the_kdf_salt() {
        assert_eq!(
            hex(&kdf(&key(), &[])),
            "ebdb909829820c287b7d7601fe00d5b093f4485a027311c2205e9007d5fc9c16"
        );
    }

    #[test]
    fn one_path_component_matches_the_reference() {
        assert_eq!(
            hex(&kdf(&key(), &["a"])),
            "f51f2a9aed1763f9bf8bc927befdd2f39294bea0f73fcd2ce7749cef56dbcdfa"
        );
        assert_eq!(kdf16(&key(), &["a"])[..], kdf(&key(), &["a"])[..16]);
    }

    #[test]
    fn two_path_components_match_the_reference() {
        // The nesting is what this pins: a two-level derivation is where an
        // `HMAC(HMAC(salt, a), b)` shortcut diverges, and no amount of retrying recovers from it.
        assert_eq!(
            hex(&kdf(&key(), &["a", "b"])),
            "8d33e500c86d56494f4c2cb6cd6bd9d932c1c413853e676c33a4870af13843aa"
        );
    }

    #[test]
    fn the_auth_id_key_salt_matches_the_reference() {
        assert_eq!(
            hex(&kdf16(&key(), &[SALT_AUTH_ID_ENCRYPTION_KEY])),
            "9fa4289c41650861a45b34aeab3879fe"
        );
    }

    #[test]
    fn the_header_key_derivation_matches_the_reference() {
        // The shape every request uses: a salt plus (auth_id, nonce), where the last two are raw
        // bytes rather than text.
        let auth_id = b"authid";
        let nonce = b"nonce";
        assert_eq!(
            hex(&kdf_components(
                &key(),
                &[
                    SALT_HEADER_PAYLOAD_AEAD_KEY.as_bytes().to_vec(),
                    auth_id.to_vec(),
                    nonce.to_vec(),
                ]
            )),
            "1b362c550d91f34902479e6023dda1adbbf93409677e65e722fdbdfda257a5af"
        );

        // A different salt at the same position gives a different key, or the length and the
        // payload would be sealed under one key.
        assert_ne!(
            hex(&kdf_components(
                &key(),
                &[
                    SALT_HEADER_PAYLOAD_LENGTH_AEAD_KEY.as_bytes().to_vec(),
                    auth_id.to_vec(),
                    nonce.to_vec(),
                ]
            )),
            "1b362c550d91f34902479e6023dda1adbbf93409677e65e722fdbdfda257a5af"
        );
    }

    #[test]
    fn a_path_component_that_is_not_utf8_still_derives_the_references_key() {
        // Go passes `string(authid)` and `string(nonce)`: raw bytes. A `&str` round trip would
        // mangle these, which is why `kdf_components` exists.
        assert_eq!(
            hex(&kdf_components(
                &key(),
                &[
                    SALT_HEADER_PAYLOAD_LENGTH_AEAD_IV.as_bytes().to_vec(),
                    vec![0x01, 0x02],
                    vec![0x03, 0x04, 0x05, 0x06, 0x07, 0x08],
                ]
            )),
            "3749b24468c92e3a440b89f6f4a55a910d1f33b474e90ddc006a93fe0590cd7c"
        );
    }

    #[test]
    fn the_cmd_key_is_md5_of_the_uuid_and_the_reference_constant() {
        // `common/protocol/id.go`: `md5(uuid ‖ "c48619fe-…")`.
        let uuid: [u8; 16] = [
            0xf0, 0xf1, 0xf2, 0xf3, 0xf4, 0xf5, 0xf6, 0xf7, 0xf8, 0xf9, 0xfa, 0xfb, 0xfc, 0xfd,
            0xfe, 0xff,
        ];
        assert_eq!(hex(&cmd_key(&uuid)), "164becf52b658fe09db0fbc4cb3a8d04");
        assert_ne!(cmd_key(&[0u8; 16]), cmd_key(&uuid));
    }
}
